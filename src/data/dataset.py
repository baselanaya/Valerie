@dataclass
class DataSample:
    """Data sample structure for Valerie dataset with two-stage visual speech recognition support."""
    
    # Video data (primary input for visual-only training)
    video_frames: torch.Tensor  # [T, H, W, C] or [C, T, H, W]
    video_path: Optional[str] = None
    
    # Two-stage training data (generated by ASR pipeline)
    transcription: Optional[str] = None  # Generated by Whisper ASR
    phoneme_sequence: Optional[List[str]] = None  # Generated from transcription
    phoneme_alignment: Optional[List[Tuple[int, int, str]]] = None  # (start_frame, end_frame, phoneme)
    phoneme_logits: Optional[torch.Tensor] = None  # For phoneme-to-text training
    
    # Audio data (optional - not used in visual-only training)
    audio_waveform: Optional[torch.Tensor] = None  # [T_audio] - for reference only
    audio_path: Optional[str] = None
    
    # Metadata
    speaker_id: Optional[str] = None
    language: str = "en"
    duration: Optional[float] = None
    
    # Quality metrics
    face_confidence: Optional[float] = None
    transcription_confidence: Optional[float] = None  # Whisper confidence
    phoneme_confidence: Optional[float] = None
    
    # Two-stage training indicators
    stage1_target: Optional[torch.Tensor] = None  # Phoneme targets for Stage 1
    stage2_target: Optional[str] = None  # Text targets for Stage 2


class EnhancedVoxCeleb2Dataset(Dataset):
    """
    Enhanced VoxCeleb2 dataset loader using generated transcriptions and phonemes.
    
    This dataset loader implements a two-stage visual speech recognition approach:
    - Uses only video files (visual-only training, no audio dependency)
    - Loads generated transcriptions from Whisper ASR
    - Loads generated phoneme sequences for two-stage training
    - Supports Stage 1 (Video → Phonemes) and Stage 2 (Phonemes → Text) training
    
    Expected structure:
    voxceleb2_root/
        dev/mp4/id00012/21Uxsk56VDQ/00001.mp4, 00002.mp4, ...
        test/mp4/...
    transcriptions/
        id00012_21Uxsk56VDQ_00001.json, id00012_21Uxsk56VDQ_00002.json, ...
    phonemes/
        id00012_21Uxsk56VDQ_00001.json, id00012_21Uxsk56VDQ_00002.json, ...
    """
    
    def __init__(
        self,
        voxceleb2_root: str,
        transcription_dir: str,
        phoneme_dir: str,
        split: str = "dev",
        training_stage: str = "stage1",  # "stage1", "stage2", or "both"
        max_sequence_length: int = 500,
        frame_rate: int = 25,
        target_height: int = 224,
        target_width: int = 224,
        max_samples: Optional[int] = None,
        quality_filter: bool = True,
        min_duration: float = 1.0,
        max_duration: float = 10.0,
        phoneme_vocab_size: int = 40
    ):
        """
        Initialize enhanced VoxCeleb2 dataset with two-stage training support.
        
        Args:
            voxceleb2_root: Path to VoxCeleb2 dataset root directory
            transcription_dir: Path to generated transcriptions directory
            phoneme_dir: Path to generated phonemes directory
            split: Dataset split ("dev" or "test")
            training_stage: Training stage ("stage1", "stage2", or "both")
            max_sequence_length: Maximum number of video frames
            frame_rate: Target video frame rate
            target_height: Target video frame height
            target_width: Target video frame width
            max_samples: Maximum number of samples to load (for debugging)
            quality_filter: Whether to apply quality filtering
            min_duration: Minimum audio duration in seconds
            max_duration: Maximum audio duration in seconds
            phoneme_vocab_size: Size of phoneme vocabulary
        """
        super().__init__()
        
        self.voxceleb2_root = Path(voxceleb2_root)
        self.transcription_dir = Path(transcription_dir)
        self.phoneme_dir = Path(phoneme_dir)
        self.split = split
        self.training_stage = training_stage
        self.max_sequence_length = max_sequence_length
        self.frame_rate = frame_rate
        self.target_height = target_height
        self.target_width = target_width
        self.quality_filter = quality_filter
        self.min_duration = min_duration
        self.max_duration = max_duration
        self.phoneme_vocab_size = phoneme_vocab_size
        
        logger.info(f"🎯 Loading enhanced VoxCeleb2 dataset ({split} split, {training_stage} training)...")
        logger.info(f"   VoxCeleb2 root: {voxceleb2_root}")
        logger.info(f"   Transcription dir: {transcription_dir}")
        logger.info(f"   Phoneme dir: {phoneme_dir}")
        logger.info(f"   Training stage: {training_stage}")
        logger.info(f"   Max sequence length: {max_sequence_length}")
        logger.info(f"   Target resolution: {target_height}x{target_width}")
        
        try:
            # Build file index with transcription and phoneme matching
            self.file_index = self._build_enhanced_file_index()
            
            if max_samples:
                self.file_index = self.file_index[:max_samples]
            
            logger.info(f"✅ Enhanced VoxCeleb2 dataset loaded: {len(self.file_index)} samples")
            
            # Load phoneme vocabulary
            self.phoneme_vocab = self._build_phoneme_vocab()
            logger.info(f"✅ Phoneme vocabulary: {len(self.phoneme_vocab)} phonemes")
            
        except Exception as e:
            logger.error(f"❌ Failed to load enhanced VoxCeleb2 dataset: {e}")
            raise
        
        # Initialize face detector for lip region extraction
        try:
            import cv2
            self.face_cascade = cv2.CascadeClassifier(cv2.data.haarcascades + 'haarcascade_frontalface_default.xml')
            logger.info("✅ Face detector initialized")
        except Exception as e:
            logger.warning(f"⚠️ Face detector initialization failed: {e}")
            self.face_cascade = None
    
    def __len__(self) -> int:
        return len(self.file_index)
    
    def __getitem__(self, idx: int) -> DataSample:
        """Get a single data sample for two-stage visual speech recognition training."""
        try:
            # Get file info from index
            file_info = self.file_index[idx]
            return self._process_enhanced_sample(file_info)
            
        except Exception as e:
            logger.warning(f"⚠️ Error processing enhanced sample {idx}: {e}")
            # Return a dummy sample to avoid breaking training
            return self._create_enhanced_dummy_sample()
    
    def _build_enhanced_file_index(self) -> List[Dict[str, str]]:
        """Build index of video files with matching transcriptions and phonemes."""
        
        split_dir = self.voxceleb2_root / self.split / "mp4"
        if not split_dir.exists():
            raise FileNotFoundError(f"Split directory not found: {split_dir}")
        
        file_index = []
        
        # Find all MP4 files
        for video_file in split_dir.rglob("*.mp4"):
            # Extract identifiers from path: id00012/21Uxsk56VDQ/00001.mp4
            parts = video_file.parts
            if len(parts) < 3:
                continue
                
            speaker_id = parts[-3]
            session_name = parts[-2]
            utterance_id = video_file.stem
            
            # Build base name for transcription and phoneme files
            base_name = f"{speaker_id}_{session_name}_{utterance_id}"
            
            # Check for matching transcription and phoneme files
            transcription_file = self.transcription_dir / f"{base_name}.json"
            phoneme_file = self.phoneme_dir / f"{base_name}.json"
            
            # Only include samples that have both transcription and phonemes
            if transcription_file.exists() and phoneme_file.exists():
                file_info = {
                    'speaker_id': speaker_id,
                    'session_name': session_name,
                    'utterance_id': utterance_id,
                    'base_name': base_name,
                    'video_path': str(video_file),
                    'transcription_path': str(transcription_file),
                    'phoneme_path': str(phoneme_file)
                }
                file_index.append(file_info)
        
        logger.info(f"📁 Built enhanced file index: {len(file_index)} utterances with complete data")
        return file_index
    
    def _build_phoneme_vocab(self) -> Dict[str, int]:
        """Build phoneme vocabulary from all phoneme files."""
        phoneme_set = set()
        
        # Sample a subset of phoneme files to build vocabulary
        sample_size = min(1000, len(self.file_index))
        sample_indices = np.random.choice(len(self.file_index), sample_size, replace=False)
        
        for idx in sample_indices:
            file_info = self.file_index[idx]
            try:
                with open(file_info['phoneme_path'], 'r', encoding='utf-8') as f:
                    phoneme_data = json.load(f)
                    phonemes = phoneme_data.get('phonemes', [])
                    phoneme_set.update(phonemes)
            except Exception as e:
                logger.debug(f"⚠️ Failed to load phonemes from {file_info['phoneme_path']}: {e}")
                continue
        
        # Create vocabulary mapping
        vocab = {'<PAD>': 0, '<UNK>': 1, '<SOS>': 2, '<EOS>': 3}
        for i, phoneme in enumerate(sorted(phoneme_set), start=4):
            vocab[phoneme] = i
        
        return vocab
    
    def _process_enhanced_sample(self, file_info: Dict[str, str]) -> DataSample:
        """Process a VoxCeleb2 sample for two-stage visual speech recognition training."""
        
        # Load video frames (primary input)
        video_path = file_info['video_path']
        video_frames = self._load_video_frames_enhanced(video_path)
        
        if video_frames is None:
            return self._create_enhanced_dummy_sample()
        
        # Load transcription data
        transcription_data = self._load_transcription_data(file_info['transcription_path'])
        transcription = transcription_data.get('text', '')
        transcription_confidence = transcription_data.get('confidence', 0.0)
        duration = transcription_data.get('duration', 2.0)
        
        # Load phoneme data
        phoneme_data = self._load_phoneme_data(file_info['phoneme_path'])
        phoneme_sequence = phoneme_data.get('phonemes', [])
        phoneme_confidence = phoneme_data.get('confidence', 0.0)
        
        # Apply quality filtering
        if self.quality_filter:
            if duration < self.min_duration or duration > self.max_duration:
                return self._create_enhanced_dummy_sample()
            
            if transcription_confidence < 0.1:  # Very low confidence
                return self._create_enhanced_dummy_sample()
        
        # Prepare training targets based on stage
        stage1_target = None
        stage2_target = None
        
        if self.training_stage in ["stage1", "both"]:
            # Stage 1: Video → Phonemes (CTC targets)
            stage1_target = self._phonemes_to_tensor(phoneme_sequence)
        
        if self.training_stage in ["stage2", "both"]:
            # Stage 2: Phonemes → Text (language modeling targets)
            stage2_target = transcription
        
        return DataSample(
            video_frames=video_frames,
            video_path=video_path,
            transcription=transcription,
            phoneme_sequence=phoneme_sequence,
            speaker_id=file_info['speaker_id'],
            language="en",
            duration=duration,
            transcription_confidence=transcription_confidence,
            phoneme_confidence=phoneme_confidence,
            stage1_target=stage1_target,
            stage2_target=stage2_target
        )
    
    def _load_video_frames_enhanced(self, video_path: str) -> Optional[torch.Tensor]:
        """Load video frames optimized for visual speech recognition (face-focused)."""
        try:
            cap = cv2.VideoCapture(video_path)
            fps = cap.get(cv2.CAP_PROP_FPS)
            frame_count = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
            
            if fps <= 0 or frame_count <= 0:
                cap.release()
                return None
            
            # Calculate duration and target frames
            duration = frame_count / fps
            target_frames = min(int(duration * self.frame_rate), self.max_sequence_length)
            step = max(1, frame_count // target_frames)
            
            frames = []
            frame_idx = 0
            
            while len(frames) < target_frames:
                cap.set(cv2.CAP_PROP_POS_FRAMES, frame_idx)
                ret, frame = cap.read()
                
                if not ret:
                    break
                
                # Process frame for visual speech recognition (frames are already face-cropped)
                processed_frame = self._process_face_frame(frame)
                frames.append(processed_frame)
                
                frame_idx += step
            
            cap.release()
            
            if frames:
                # Convert to tensor [T, H, W, C] and normalize to [0, 1]
                video_tensor = torch.from_numpy(np.stack(frames)).float() / 255.0
                return video_tensor
            else:
                return None
                
        except Exception as e:
            logger.warning(f"⚠️ Failed to load video {video_path}: {e}")
            return None
    
    def _process_face_frame(self, frame: np.ndarray) -> np.ndarray:
        """
        Process face frame for visual speech recognition.
        
        Since VoxCeleb2 MP4 files are already cropped to face regions,
        we primarily need to resize and convert color space.
        """
        # Convert BGR to RGB for consistency with model expectations
        rgb_frame = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
        
        # Resize to target dimensions
        processed_frame = cv2.resize(rgb_frame, (self.target_width, self.target_height))
        
        # Optional: Further crop to focus on mouth region if face detector is available
        if self.face_cascade is not None:
            try:
                gray = cv2.cvtColor(rgb_frame, cv2.COLOR_RGB2GRAY)
                faces = self.face_cascade.detectMultiScale(gray, 1.1, 4)
                
                if len(faces) > 0:
                    # Take the largest face
                    x, y, w, h = max(faces, key=lambda f: f[2] * f[3])
                    
                    # Extract lower portion focusing on mouth area
                    mouth_y = y + int(h * 0.5)  # Start from middle of detected face
                    mouth_h = int(h * 0.5)      # Take lower half
                    mouth_x = x + int(w * 0.1)  # Slightly crop sides
                    mouth_w = int(w * 0.8)      # Take 80% of width
                    
                    # Ensure we don't go out of bounds
                    mouth_y = max(0, mouth_y)
                    mouth_x = max(0, mouth_x)
                    mouth_h = min(rgb_frame.shape[0] - mouth_y, mouth_h)
                    mouth_w = min(rgb_frame.shape[1] - mouth_x, mouth_w)
                    
                    if mouth_h > 0 and mouth_w > 0:
                        mouth_region = rgb_frame[mouth_y:mouth_y + mouth_h, mouth_x:mouth_x + mouth_w]
                        processed_frame = cv2.resize(mouth_region, (self.target_width, self.target_height))
                        
            except Exception as e:
                # If face detection fails, use the resized frame
                logger.debug(f"Face detection failed, using full frame: {e}")
        
        return processed_frame
    
    def _load_transcription_data(self, transcription_path: str) -> Dict:
        """Load transcription data from JSON file."""
        try:
            with open(transcription_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
                transcription_info = data.get('transcription', {})
                return {
                    'text': transcription_info.get('text', ''),
                    'confidence': transcription_info.get('probability', 0.0),
                    'duration': transcription_info.get('duration', 0.0),
                    'language': transcription_info.get('language', 'en')
                }
        except Exception as e:
            logger.warning(f"⚠️ Failed to load transcription {transcription_path}: {e}")
            return {'text': '', 'confidence': 0.0, 'duration': 0.0, 'language': 'en'}
    
    def _load_phoneme_data(self, phoneme_path: str) -> Dict:
        """Load phoneme data from JSON file."""
        try:
            with open(phoneme_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
                return {
                    'phonemes': data.get('phonemes', []),
                    'confidence': 1.0,  # Assume good confidence for rule-based conversion
                    'phoneme_count': data.get('phoneme_count', 0)
                }
        except Exception as e:
            logger.warning(f"⚠️ Failed to load phonemes {phoneme_path}: {e}")
            return {'phonemes': [], 'confidence': 0.0, 'phoneme_count': 0}
    
    def _phonemes_to_tensor(self, phoneme_sequence: List[str]) -> torch.Tensor:
        """Convert phoneme sequence to tensor indices."""
        indices = []
        for phoneme in phoneme_sequence:
            idx = self.phoneme_vocab.get(phoneme, self.phoneme_vocab['<UNK>'])
            indices.append(idx)
        return torch.tensor(indices, dtype=torch.long)
    
    def _create_enhanced_dummy_sample(self) -> DataSample:
        """Create a dummy sample for two-stage training error cases."""
        duration = 2.0
        num_frames = int(duration * self.frame_rate)
        
        # Create dummy video frames (RGB format for visual speech recognition)
        video_frames = torch.zeros(num_frames, self.target_height, self.target_width, 3)
        
        # Create dummy phoneme targets
        dummy_phonemes = ['SIL', 'D', 'AH', 'M', 'IY', 'SIL']
        stage1_target = self._phonemes_to_tensor(dummy_phonemes)
        
        return DataSample(
            video_frames=video_frames,
            transcription="dummy sample",
            phoneme_sequence=dummy_phonemes,
            speaker_id="dummy",
            language="en",
            duration=duration,
            transcription_confidence=0.0,
            phoneme_confidence=0.0,
            stage1_target=stage1_target,
            stage2_target="dummy sample"
        )


class VoxCeleb2Dataset(Dataset):
    """
    VoxCeleb2 dataset loader for local VoxCeleb2 files.
    
    VoxCeleb2 contains over 1M utterances from 6,112 celebrities with:
    - Audio recordings extracted from YouTube videos (.m4a files)
    - Video recordings with face regions (.mp4 files)
    - Transcriptions for each utterance (.txt files)
    - Speaker diversity across accents and recording conditions
    
    Expected structure:
    voxceleb2_root/
        dev/
            aac/id00012/21Uxsk56VDQ/00001.m4a, 00002.m4a, ...
            mp4/id00012/21Uxsk56VDQ/00001.mp4, 00002.mp4, ...
            txt/id00012/21Uxsk56VDQ/00001.txt, 00002.txt, ...
        test/
            aac/...
            mp4/...
            txt/...
        vox2_meta.csv
    
    Data source: https://www.robots.ox.ac.uk/~vgg/data/voxceleb/vox2.html
    """
    
    def __init__(
        self,
        voxceleb2_root: str,
        split: str = "dev",
        max_sequence_length: int = 500,
        frame_rate: int = 25,
        audio_sample_rate: int = 16000,
        target_height: int = 224,
        target_width: int = 224,
        num_workers: int = 4,
        max_samples: Optional[int] = None,
        quality_filter: bool = True,
        min_duration: float = 1.0,
        max_duration: float = 10.0,
        use_video: bool = True,
        use_transcriptions: bool = True
    ):
        """
        Initialize VoxCeleb2 dataset.
        
        Args:
            voxceleb2_root: Path to VoxCeleb2 dataset root directory
            split: Dataset split ("dev" or "test")
            max_sequence_length: Maximum number of video frames
            frame_rate: Target video frame rate
            audio_sample_rate: Target audio sample rate
            target_height: Target video frame height
            target_width: Target video frame width
            num_workers: Number of workers for data loading
            max_samples: Maximum number of samples to load (for debugging)
            quality_filter: Whether to apply quality filtering
            min_duration: Minimum audio duration in seconds
            max_duration: Maximum audio duration in seconds
            use_video: Whether to load video files (.mp4)
            use_transcriptions: Whether to load transcription files (.txt)
        """
        super().__init__()
        
        self.voxceleb2_root = Path(voxceleb2_root)
        self.split = split
        self.max_sequence_length = max_sequence_length
        self.frame_rate = frame_rate
        self.audio_sample_rate = audio_sample_rate
        self.target_height = target_height
        self.target_width = target_width
        self.num_workers = num_workers
        self.quality_filter = quality_filter
        self.min_duration = min_duration
        self.max_duration = max_duration
        self.use_video = use_video
        self.use_transcriptions = use_transcriptions
        
        logger.info(f"📊 Loading VoxCeleb2 dataset ({split} split)...")
        logger.info(f"   Root directory: {voxceleb2_root}")
        logger.info(f"   Max sequence length: {max_sequence_length}")
        logger.info(f"   Frame rate: {frame_rate} FPS")
        logger.info(f"   Audio sample rate: {audio_sample_rate} Hz")
        logger.info(f"   Target resolution: {target_height}x{target_width}")
        logger.info(f"   Use video: {use_video}")
        logger.info(f"   Use transcriptions: {use_transcriptions}")
        
        try:
            # Load metadata
            metadata_path = self.voxceleb2_root / "vox2_meta.csv"
            if not metadata_path.exists():
                raise FileNotFoundError(f"Metadata file not found: {metadata_path}")
            
            self.metadata = pd.read_csv(metadata_path)
            self.metadata.columns = self.metadata.columns.str.strip()  # Clean column names
            logger.info(f"✅ Loaded metadata: {len(self.metadata)} speakers")
            
            # Build file index for the specified split
            self.file_index = self._build_file_index()
            
            if max_samples:
                self.file_index = self.file_index[:max_samples]
            
            logger.info(f"✅ VoxCeleb2 dataset loaded: {len(self.file_index)} samples")
            
        except Exception as e:
            logger.error(f"❌ Failed to load VoxCeleb2 dataset: {e}")
            raise
        
        # Initialize face detector for lip region extraction
        try:
            import cv2
            self.face_cascade = cv2.CascadeClassifier(cv2.data.haarcascades + 'haarcascade_frontalface_default.xml')
            logger.info("✅ Face detector initialized")
        except Exception as e:
            logger.warning(f"⚠️ Face detector initialization failed: {e}")
            self.face_cascade = None
    
    def __len__(self) -> int:
        return len(self.file_index)
    
    def __getitem__(self, idx: int) -> DataSample:
        """Get a single data sample."""
        try:
            # Get file info from index
            file_info = self.file_index[idx]
            return self._process_voxceleb2_sample(file_info)
            
        except Exception as e:
            logger.warning(f"⚠️ Error processing sample {idx}: {e}")
            # Return a dummy sample to avoid breaking training
            return self._create_dummy_sample()
    
    def _build_file_index(self) -> List[Dict[str, str]]:
        """Build index of all audio/video files for the specified split."""
        
        split_dir = self.voxceleb2_root / self.split
        if not split_dir.exists():
            raise FileNotFoundError(f"Split directory not found: {split_dir}")
        
        # Filter metadata for current split
        split_metadata = self.metadata[self.metadata['Set'].str.strip() == self.split]
        logger.info(f"📊 Found {len(split_metadata)} speakers in {self.split} split")
        
        file_index = []
        aac_dir = split_dir / "aac"
        mp4_dir = split_dir / "mp4" 
        txt_dir = split_dir / "txt"
        
        for _, row in split_metadata.iterrows():
            speaker_id = row['VoxCeleb2 ID'].strip()
            gender = row['Gender'].strip()
            
            speaker_aac_dir = aac_dir / speaker_id
            if not speaker_aac_dir.exists():
                continue
            
            # Iterate through video sessions for this speaker
            for session_dir in speaker_aac_dir.iterdir():
                if not session_dir.is_dir():
                    continue
                
                session_name = session_dir.name
                
                # Find all audio files in this session
                for audio_file in session_dir.glob("*.m4a"):
                    utterance_id = audio_file.stem
                    
                    # Build paths for all modalities
                    video_path = mp4_dir / speaker_id / session_name / f"{utterance_id}.mp4"
                    txt_path = txt_dir / speaker_id / session_name / f"{utterance_id}.txt"
                    
                    file_info = {
                        'speaker_id': speaker_id,
                        'session_name': session_name,
                        'utterance_id': utterance_id,
                        'gender': gender,
                        'audio_path': str(audio_file),
                        'video_path': str(video_path) if video_path.exists() else None,
                        'txt_path': str(txt_path) if txt_path.exists() else None
                    }
                    
                    file_index.append(file_info)
        
        logger.info(f"📁 Built file index: {len(file_index)} utterances")
        return file_index
    
    def _process_voxceleb2_sample(self, file_info: Dict[str, str]) -> DataSample:
        """Process a VoxCeleb2 sample from file paths."""
        
        # Load audio
        audio_path = file_info['audio_path']
        try:
            audio_array, sr = librosa.load(audio_path, sr=self.audio_sample_rate)
            audio_waveform = torch.from_numpy(audio_array).float()
            duration = len(audio_array) / self.audio_sample_rate
        except Exception as e:
            logger.warning(f"⚠️ Failed to load audio {audio_path}: {e}")
            duration = 2.0
            audio_waveform = torch.zeros(int(duration * self.audio_sample_rate))
        
        # Apply quality filtering
        if self.quality_filter:
            if duration < self.min_duration or duration > self.max_duration:
                return self._create_dummy_sample()
        
        # Load video if available
        video_frames = None
        if self.use_video and file_info['video_path']:
            video_frames = self._load_video_frames(file_info['video_path'], duration)
        
        if video_frames is None:
            video_frames = self._create_placeholder_video(duration)
        
        # Load transcription if available
        transcription = None
        transcription_confidence = 0.0
        if self.use_transcriptions and file_info['txt_path']:
            try:
                with open(file_info['txt_path'], 'r', encoding='utf-8') as f:
                    transcription = f.read().strip()
                    transcription_confidence = 1.0
            except Exception as e:
                logger.debug(f"⚠️ Failed to load transcription {file_info['txt_path']}: {e}")
        
        return DataSample(
            video_frames=video_frames,
            audio_waveform=audio_waveform,
            video_path=file_info['video_path'],
            audio_path=file_info['audio_path'],
            transcription=transcription,
            speaker_id=file_info['speaker_id'],
            language="en",  # VoxCeleb2 is English
            duration=duration,
            transcription_confidence=transcription_confidence
        )
    
    def _load_video_frames(self, video_path: str, duration: float) -> Optional[torch.Tensor]:
        """Load video frames from MP4 file."""
        try:
            cap = cv2.VideoCapture(video_path)
            fps = cap.get(cv2.CAP_PROP_FPS)
            frame_count = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
            
            if fps <= 0 or frame_count <= 0:
                cap.release()
                return None
            
            # Calculate target frames
            target_frames = min(int(duration * self.frame_rate), self.max_sequence_length)
            step = max(1, frame_count // target_frames)
            
            frames = []
            frame_idx = 0
            
            while len(frames) < target_frames:
                cap.set(cv2.CAP_PROP_POS_FRAMES, frame_idx)
                ret, frame = cap.read()
                
                if not ret:
                    break
                
                # Extract lip region if face detector is available
                if self.face_cascade is not None:
                    processed_frame = self.extract_lip_region(frame)
                else:
                    processed_frame = cv2.resize(frame, (self.target_width, self.target_height))
                
                # Convert BGR to RGB and normalize
                processed_frame = cv2.cvtColor(processed_frame, cv2.COLOR_BGR2RGB)
                frames.append(processed_frame)
                
                frame_idx += step
            
            cap.release()
            
            if frames:
                # Convert to tensor and normalize to [0, 1]
                video_tensor = torch.from_numpy(np.stack(frames)).float() / 255.0
                return video_tensor
            else:
                return None
                
        except Exception as e:
            logger.warning(f"⚠️ Failed to load video {video_path}: {e}")
            return None
    
    def _create_placeholder_video(self, duration: float) -> torch.Tensor:
        """Create placeholder video frames for audio-only data."""
        num_frames = min(int(duration * self.frame_rate), self.max_sequence_length)
        
        # Create dummy frames (black with some noise for realism)
        frames = torch.zeros(num_frames, self.target_height, self.target_width, 3)
        frames += torch.randn_like(frames) * 0.1  # Add some noise
        
        return frames
    
    def _create_dummy_sample(self) -> DataSample:
        """Create a dummy sample for error cases."""
        duration = 2.0
        num_frames = int(duration * self.frame_rate)
        
        return DataSample(
            video_frames=torch.zeros(num_frames, self.target_height, self.target_width, 3),
            audio_waveform=torch.zeros(int(duration * self.audio_sample_rate)),
            transcription="dummy sample",
            speaker_id="dummy",
            language="en",
            duration=duration,
            transcription_confidence=0.0
        )
    
    def extract_lip_region(self, frame: np.ndarray) -> np.ndarray:
        """Extract lip region from face using simple face detection."""
        if self.face_cascade is None:
            return cv2.resize(frame, (self.target_width, self.target_height))
        
        gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY) if len(frame.shape) == 3 else frame
        faces = self.face_cascade.detectMultiScale(gray, 1.1, 4)
        
        if len(faces) > 0:
            # Take the largest face
            x, y, w, h = max(faces, key=lambda f: f[2] * f[3])
            
            # Extract lower half of face (lip region)
            lip_y = y + h // 2
            lip_h = h // 2
            lip_region = frame[lip_y:lip_y + lip_h, x:x + w]
            
            return cv2.resize(lip_region, (self.target_width, self.target_height))
        else:
            # No face detected, return resized original
            return cv2.resize(frame, (self.target_width, self.target_height))


class AVSpeechDataset(Dataset):
    """
    AVSpeech dataset loader for audio-visual speech recognition.
    
    AVSpeech contains 270k training and 22k test video segments with:
    - YouTube video segments with face coordinates
    - Clean audio-visual segments for speech recognition
    - Speaker-disjoint train/test splits
    
    Data format from CSV:
    YouTube ID, start segment, end segment, X coordinate, Y coordinate
    
    Data source: https://looking-to-listen.github.io/avspeech/download.html
    """
    
    def __init__(
        self,
        csv_path: str,
        video_root: Optional[str] = None,
        split: str = "train",
        max_sequence_length: int = 500,
        frame_rate: int = 25,
        audio_sample_rate: int = 16000,
        target_height: int = 224,
        target_width: int = 224,
        download_videos: bool = False,
        max_samples: Optional[int] = None,
        quality_filter: bool = True
    ):
        """
        Initialize AVSpeech dataset.
        
        Args:
            csv_path: Path to train.csv or test.csv
            video_root: Root directory for downloaded videos
            split: Dataset split ("train" or "test")
            max_sequence_length: Maximum number of video frames
            frame_rate: Target video frame rate
            audio_sample_rate: Target audio sample rate
            target_height: Target video frame height
            target_width: Target video frame width
            download_videos: Whether to download videos from YouTube
            max_samples: Maximum number of samples to load
            quality_filter: Whether to apply quality filtering
        """
        super().__init__()
        
        self.csv_path = Path(csv_path)
        self.video_root = Path(video_root) if video_root else None
        self.split = split
        self.max_sequence_length = max_sequence_length
        self.frame_rate = frame_rate
        self.audio_sample_rate = audio_sample_rate
        self.target_height = target_height
        self.target_width = target_width
        self.download_videos = download_videos
        self.quality_filter = quality_filter
        
        logger.info(f"📊 Loading AVSpeech dataset ({split} split)...")
        logger.info(f"   CSV path: {csv_path}")
        logger.info(f"   Video root: {video_root}")
        logger.info(f"   Download videos: {download_videos}")
        
        # Load CSV data
        try:
            self.data = pd.read_csv(csv_path, names=[
                'youtube_id', 'start_time', 'end_time', 'face_x', 'face_y'
            ])
            
            if max_samples:
                self.data = self.data.head(max_samples)
            
            logger.info(f"✅ AVSpeech CSV loaded: {len(self.data)} segments")
            
        except Exception as e:
            logger.error(f"❌ Failed to load AVSpeech CSV: {e}")
            raise
        
        # Initialize video downloader if needed
        if download_videos:
            try:
                import yt_dlp
                self.ydl_opts = {
                    'format': 'best[height<=480]',  # Reasonable quality
                    'outtmpl': str(self.video_root / '%(id)s.%(ext)s'),
                    'quiet': True,
                    'no_warnings': True,
                }
                logger.info("✅ YouTube downloader initialized")
            except ImportError:
                logger.error("❌ yt-dlp not installed. Install with: pip install yt-dlp")
                self.download_videos = False
    
    def __len__(self) -> int:
        return len(self.data)
    
    def __getitem__(self, idx: int) -> DataSample:
        """Get a single data sample."""
        try:
            row = self.data.iloc[idx]
            return self._process_avspeech_sample(row)
            
        except Exception as e:
            logger.warning(f"⚠️ Error processing AVSpeech sample {idx}: {e}")
            return self._create_dummy_sample()
    
    def _process_avspeech_sample(self, row: pd.Series) -> DataSample:
        """Process a single AVSpeech sample."""
        
        youtube_id = row['youtube_id']
        start_time = row['start_time']
        end_time = row['end_time']
        face_x = row['face_x']
        face_y = row['face_y']
        
        duration = end_time - start_time
        
        # Check if video exists locally
        video_path = None
        if self.video_root:
            for ext in ['.mp4', '.mkv', '.webm']:
                potential_path = self.video_root / f"{youtube_id}{ext}"
                if potential_path.exists():
                    video_path = potential_path
                    break
        
        # Download video if needed and enabled
        if video_path is None and self.download_videos:
            video_path = self._download_video(youtube_id)
        
        if video_path and video_path.exists():
            # Extract video frames and audio
            video_frames, audio_waveform = self._extract_video_audio(
                video_path, start_time, end_time, face_x, face_y
            )
        else:
            # Create placeholder data
            video_frames = self._create_placeholder_video(duration)
            audio_waveform = torch.zeros(int(duration * self.audio_sample_rate))
        
        return DataSample(
            video_frames=video_frames,
            audio_waveform=audio_waveform,
            video_path=str(video_path) if video_path else None,
            transcription=None,  # AVSpeech doesn't provide transcriptions
            speaker_id=youtube_id,
            duration=duration,
            face_confidence=1.0  # Assume good face detection from coordinates
        )
    
    def _download_video(self, youtube_id: str) -> Optional[Path]:
        """Download video from YouTube."""
        if not self.download_videos:
            return None
        
        try:
            import yt_dlp
            
            url = f"https://www.youtube.com/watch?v={youtube_id}"
            
            with yt_dlp.YoutubeDL(self.ydl_opts) as ydl:
                ydl.download([url])
            
            # Find the downloaded file
            for ext in ['.mp4', '.mkv', '.webm']:
                video_path = self.video_root / f"{youtube_id}{ext}"
                if video_path.exists():
                    return video_path
            
            return None
            
        except Exception as e:
            logger.warning(f"⚠️ Failed to download video {youtube_id}: {e}")
            return None
    
    def _extract_video_audio(
        self, 
        video_path: Path, 
        start_time: float, 
        end_time: float,
        face_x: float, 
        face_y: float
    ) -> Tuple[torch.Tensor, torch.Tensor]:
        """Extract video frames and audio from video file."""
        
        try:
            # Open video
            cap = cv2.VideoCapture(str(video_path))
            fps = cap.get(cv2.CAP_PROP_FPS)
            
            # Calculate frame indices
            start_frame = int(start_time * fps)
            end_frame = int(end_time * fps)
            
            # Extract frames
            frames = []
            cap.set(cv2.CAP_PROP_POS_FRAMES, start_frame)
            
            for frame_idx in range(start_frame, end_frame):
                ret, frame = cap.read()
                if not ret:
                    break
                
                # Extract face region using provided coordinates
                face_frame = self._extract_face_region(frame, face_x, face_y)
                frames.append(face_frame)
            
            cap.release()
            
            # Convert to tensor
            if frames:
                video_frames = torch.from_numpy(np.stack(frames)).float() / 255.0
            else:
                duration = end_time - start_time
                video_frames = self._create_placeholder_video(duration)
            
            # Extract audio using librosa
            try:
                audio, sr = librosa.load(
                    str(video_path), 
                    sr=self.audio_sample_rate,
                    offset=start_time,
                    duration=end_time - start_time
                )
                audio_waveform = torch.from_numpy(audio).float()
            except:
                # Fallback to silent audio
                duration = end_time - start_time
                audio_waveform = torch.zeros(int(duration * self.audio_sample_rate))
            
            return video_frames, audio_waveform
            
        except Exception as e:
            logger.warning(f"⚠️ Error extracting video/audio: {e}")
            duration = end_time - start_time
            return (
                self._create_placeholder_video(duration),
                torch.zeros(int(duration * self.audio_sample_rate))
            )
    
    def _extract_face_region(self, frame: np.ndarray, face_x: float, face_y: float) -> np.ndarray:
        """Extract face region using provided coordinates."""
        h, w = frame.shape[:2]
        
        # Convert normalized coordinates to pixel coordinates
        center_x = int(face_x * w)
        center_y = int(face_y * h)
        
        # Define face region size (adjust as needed)
        face_size = min(w, h) // 3
        
        # Extract region around face center
        x1 = max(0, center_x - face_size // 2)
        y1 = max(0, center_y - face_size // 2)
        x2 = min(w, center_x + face_size // 2)
        y2 = min(h, center_y + face_size // 2)
        
        face_region = frame[y1:y2, x1:x2]
        
        # Resize to target size
        face_region = cv2.resize(face_region, (self.target_width, self.target_height))
        
        return face_region
    
    def _create_placeholder_video(self, duration: float) -> torch.Tensor:
        """Create placeholder video frames."""
        num_frames = min(int(duration * self.frame_rate), self.max_sequence_length)
        frames = torch.zeros(num_frames, self.target_height, self.target_width, 3)
        return frames
    
    def _create_dummy_sample(self) -> DataSample:
        """Create a dummy sample for error cases."""
        duration = 2.0
        num_frames = int(duration * self.frame_rate)
        
        return DataSample(
            video_frames=torch.zeros(num_frames, self.target_height, self.target_width, 3),
            audio_waveform=torch.zeros(int(duration * self.audio_sample_rate)),
            transcription="dummy sample",
            speaker_id="dummy",
            duration=duration,
            face_confidence=0.0
        )


def create_dataloader(
    dataset: Dataset,
    batch_size: int = 8,
    shuffle: bool = True,
    num_workers: int = 4,
    pin_memory: bool = True,
    collate_fn: Optional[callable] = None
) -> DataLoader:
    """
    Create a DataLoader with appropriate settings.
    
    Args:
        dataset: Dataset instance
        batch_size: Batch size
        shuffle: Whether to shuffle data
        num_workers: Number of worker processes
        pin_memory: Whether to pin memory for GPU transfer
        collate_fn: Custom collate function
        
    Returns:
        Configured DataLoader
    """
    if collate_fn is None:
        collate_fn = collate_batch
    
    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=num_workers,
        pin_memory=pin_memory,
        collate_fn=collate_fn,
        persistent_workers=num_workers > 0
    )


def collate_batch(batch: List[DataSample]) -> Dict[str, torch.Tensor]:
    """
    Collate function for batching DataSample objects.
    
    Handles variable-length sequences by padding and supports two-stage visual speech recognition training.
    """
    # Separate components
    video_frames = [sample.video_frames for sample in batch]
    audio_waveforms = [sample.audio_waveform for sample in batch if sample.audio_waveform is not None]
    transcriptions = [sample.transcription for sample in batch if sample.transcription is not None]
    phoneme_sequences = [sample.phoneme_sequence for sample in batch if sample.phoneme_sequence is not None]
    
    # Pad video sequences
    max_video_length = max(frames.shape[0] for frames in video_frames)
    batch_size = len(batch)
    h, w, c = video_frames[0].shape[1:]
    
    padded_videos = torch.zeros(batch_size, max_video_length, h, w, c)
    video_lengths = torch.zeros(batch_size, dtype=torch.long)
    
    for i, frames in enumerate(video_frames):
        length = frames.shape[0]
        padded_videos[i, :length] = frames
        video_lengths[i] = length
    
    # Base batch dictionary
    batch_dict = {
        'video_frames': padded_videos,
        'video_lengths': video_lengths,
        'transcriptions': transcriptions,
        'phoneme_sequences': phoneme_sequences,
        'speaker_ids': [sample.speaker_id for sample in batch],
        'durations': torch.tensor([sample.duration or 0.0 for sample in batch]),
        'transcription_confidences': torch.tensor([sample.transcription_confidence or 0.0 for sample in batch]),
        'phoneme_confidences': torch.tensor([sample.phoneme_confidence or 0.0 for sample in batch])
    }
    
    # Add two-stage training targets
    stage1_targets = [sample.stage1_target for sample in batch if sample.stage1_target is not None]
    stage2_targets = [sample.stage2_target for sample in batch if sample.stage2_target is not None]
    
    if stage1_targets:
        # Pad phoneme target sequences for Stage 1 training
        max_phoneme_length = max(target.shape[0] for target in stage1_targets)
        padded_stage1_targets = torch.zeros(len(stage1_targets), max_phoneme_length, dtype=torch.long)
        stage1_lengths = torch.zeros(len(stage1_targets), dtype=torch.long)
        
        for i, target in enumerate(stage1_targets):
            length = target.shape[0]
            padded_stage1_targets[i, :length] = target
            stage1_lengths[i] = length
        
        batch_dict.update({
            'stage1_targets': padded_stage1_targets,
            'stage1_lengths': stage1_lengths
        })
    
    if stage2_targets:
        batch_dict['stage2_targets'] = stage2_targets
    
    # Add audio if available (for reference/validation, not used in visual-only training)
    if audio_waveforms:
        max_audio_length = max(audio.shape[0] for audio in audio_waveforms)
        padded_audio = torch.zeros(len(audio_waveforms), max_audio_length)
        audio_lengths = torch.zeros(len(audio_waveforms), dtype=torch.long)
        
        for i, audio in enumerate(audio_waveforms):
            length = audio.shape[0]
            padded_audio[i, :length] = audio
            audio_lengths[i] = length
        
        batch_dict.update({
            'audio_waveforms': padded_audio,
            'audio_lengths': audio_lengths
        })
    
    return batch_dict


def collate_enhanced_batch(batch: List[DataSample]) -> Dict[str, torch.Tensor]:
    """
    Specialized collate function for two-stage visual speech recognition training.
    
    Optimized for visual-only training with phoneme targets.
    """
    return collate_batch(batch)  # Use the enhanced collate_batch function


